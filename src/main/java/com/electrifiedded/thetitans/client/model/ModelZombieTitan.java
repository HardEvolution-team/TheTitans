    public void render(Entity entity, float f, float f1, float f2, float f3, float f4, float f5) {
        EntityZombieTitan entitytitan = (EntityZombieTitan)entity;
        playX((IAnimatedEntity)entity, f, f1, f2, f3, f4, f5);
        if (entitytitan.armedIs())
            stackHeld.isHidden = false;
        else
            stackHeld.isHidden = true;
        if (entitytitan.villagerIs())
            head2V.isHidden = false;
        else
            head2V.isHidden = true;
        if (entitytitan.isChild()) {
            head2V.isHidden = true;
            if (entitytitan.villagerIs()) {
                head22V.isHidden = false;
                head3V.isHidden = true;
            }

            else {
                head22V.isHidden = true;
                head3V.isHidden = false;
            }
        }

        else {
            head22V.isHidden = true;
            head3V.isHidden = true;
        }

        if (this.isChild) {
            float f6 = 2.0F;
            GL11.glPushMatrix();
            GL11.glScalef(1.0F / f6, 1.0F / f6, 1.0F / f6);
            GL11.glTranslatef(0.0F, 24.0F * f5, 0.0F);
            this.thighRight.render(f5);
            this.torsoV.render(f5);
            this.thighLeft.render(f5);
            GL11.glPopMatrix();
        }

        else {
            this.thighRight.render(f5);
            this.torsoV.render(f5);
            this.thighLeft.render(f5);
        }
    }

