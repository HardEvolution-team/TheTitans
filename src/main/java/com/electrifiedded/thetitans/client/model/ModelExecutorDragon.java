    @Override
    public void setRotationAngles(float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch, float scaleFactor, Entity entity) {
        float flap = MathHelper.sin(ageInTicks * 0.1F);
        this.rightwingV.rotateAngleZ = flap * 0.6F;
        this.leftwingV.rotateAngleZ = (float)Math.PI - flap * 0.6F;
        this.rightwingtipV.rotateAngleZ = MathHelper.sin(ageInTicks * 0.1F - 0.6F) * 0.4F;
        this.leftwingtipV.rotateAngleZ = this.rightwingtipV.rotateAngleZ;
        ModelRenderer[] tail = { tail1, tail2, tail3VZ, tail4V, tail5V, tail6V, tail7V, tail8V, tail9V, tail10V, tail11V, tail12V };
        for (int i = 0; i < tail.length; i++) {
            tail[i].rotateAngleY = MathHelper.sin(ageInTicks * 0.05F - i * 0.35F) * 0.06F;
            tail[i].rotateAngleX = MathHelper.cos(ageInTicks * 0.05F - i * 0.35F) * 0.03F;
        }
        ModelRenderer[] neck = { neck1V, neck2V, neck3V, neck4V, neck5V };
        float yaw = MathHelper.clamp(netHeadYaw, -60.0F, 60.0F) * 0.017453292F / (neck.length + 1);
        float pitch = headPitch * 0.017453292F / (neck.length + 1);
        for (int i = 0; i < neck.length; i++) {
            neck[i].rotateAngleY = yaw;
            neck[i].rotateAngleX = pitch + MathHelper.sin(ageInTicks * 0.1F - i * 0.3F) * 0.02F;
        }
        this.head.rotateAngleY = yaw;
        this.head.rotateAngleX = pitch;
        this.lowerjawV.rotateAngleX = (MathHelper.sin(ageInTicks * 0.1F) + 1.0F) * 0.1F;
        this.body.rotateAngleX = flap * -0.05F;
    }

